public class PolicyException extends Exception {
    private int id;

    public PolicyException(int id) {
        this.id = id;
    }

    public int getID() {
        return id;
    }

    @Override
    public String toString() {
        return "The Policy ID was not valid and a new ID (" + id
                + ") is generated by admin and assigned for the Policy";
    }
}
